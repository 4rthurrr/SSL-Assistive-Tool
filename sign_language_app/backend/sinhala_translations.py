def get_sinhala_translation(english_sign: str) -> str:
    """
    Get Sinhala translation for an English sign name
    
    Args:
        english_sign: English sign name (e.g., "Family/Mother")
        
    Returns:
        Sinhala translation if available, otherwise returns the English name
    """
    return SINHALA_TRANSLATIONS.get(english_sign, english_sign)


def get_word_only(sign_name: str) -> str:
    """
    Extract just the word from Category/Word format
    
    Args:
        sign_name: Full sign name (e.g., "Family/Mother")
        
    Returns:
        Just the word (e.g., "Mother")
    """
    if "/" in sign_name:
        return sign_name.split("/")[1]
    return sign_name


def get_display_names(sign_name: str) -> dict:
    """
    Get both English and Sinhala display names
    
    Args:
        sign_name: Full sign name (e.g., "Family/Mother")
        
    Returns:
        Dictionary with english and sinhala keys
    """
    english_word = get_word_only(sign_name)
    sinhala_word = get_sinhala_translation(sign_name)
    
    return {
        "english": english_word,
        "sinhala": sinhala_word,
        "full_english": sign_name
    }
